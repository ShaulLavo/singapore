import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { Language, Parser } from 'web-tree-sitter'
import { mapQueryCaptures } from '../src/query-captures.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(await readFile(resolve(root, 'languages.json'), 'utf8'))
const check = process.argv.includes('--check')
const quote = JSON.stringify
const ids = new Set()
const aliases = new Set()
await Parser.init()
const locks = []
const notices = []
const assetPath = (name) => resolve(root, name.startsWith('.') ? 'src' : 'node_modules', name)
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex')

for (const language of manifest.languages) {
  assert(!ids.has(language.id), `Duplicate language: ${language.id}`)
  ids.add(language.id)
  for (const alias of [language.id].concat(language.aliases)) {
    assert(!aliases.has(alias), `Ambiguous alias: ${alias}`)
    aliases.add(alias)
  }
  const files = [language.wasm].concat(
    Object.values(language.extraWasm ?? {}),
    Object.values(language.queries).flat(),
  )
  const hashes = await Promise.all(
    files.map(async (file) => ({ file, sha256: digest(await readFile(assetPath(file))) })),
  )
  const grammar = await Language.load(await readFile(assetPath(language.wasm)))
  const source = manifest.sources[language.source]
  const sourceFiles = source.package
    ? await hashSourceFiles(resolve(root, 'node_modules', source.package))
    : []
  const queries = await Promise.all(
    Object.entries(language.queries).map(async ([kind, paths]) => {
      const source = (
        await Promise.all(paths.map((file) => readFile(assetPath(file), 'utf8')))
      ).join('\n')
      return { kind, sha256: digest(mapQueryCaptures(source, manifest.captureMappings)) }
    }),
  )
  locks.push({
    id: language.id,
    parserABI: grammar.abiVersion,
    source,
    sourceFiles,
    files: hashes,
    queries,
  })
}
for (const [name, source] of Object.entries(manifest.sources)) {
  if (!source.package) {
    notices.push(
      `${name}\n${source.repository}@${source.revision}\n${await readFile(resolve(root, 'notices', `${name}.txt`), 'utf8')}`,
    )
    continue
  }
  const directory = resolve(root, 'node_modules', source.package)
  const pkg = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8'))
  assert.equal(pkg.version, source.version, `Source version changed: ${name}`)
  const license = await readFile(resolve(directory, source.licenseFile ?? 'LICENSE'), 'utf8')
  notices.push(`${name}@${source.version}\n${license}`)
}

const contributionIdentifier = (id) => `${id.replaceAll(/[^a-zA-Z0-9]+/g, '_')}Contribution`
const dependencyIdentifier = (id) => `${id.replaceAll(/[^a-zA-Z0-9]+/g, '_')}InjectionDependencies`
const languagesById = new Map(manifest.languages.map((language) => [language.id, language]))

function transitiveInjectionDependencies(id) {
  const seen = new Set([id])
  const queue = [id]
  const dependencies = []
  for (const current of queue) {
    const language = languagesById.get(current)
    for (const dependencyId of language?.injectionDependencies ?? []) {
      if (seen.has(dependencyId) || !languagesById.has(dependencyId)) continue
      seen.add(dependencyId)
      queue.push(dependencyId)
      dependencies.push(dependencyId)
    }
  }
  return dependencies
}

// One module per language: a bundler loads every module an import graph names, and Vite emits a
// grammar's .wasm when it loads the module that references it, even if the code is tree-shaken.
// A plugin that imports one language must not name the others.
const languageModule = (id) => `${id.replaceAll(/[^a-zA-Z0-9]+/g, '-')}.generated`
const fromLanguageDirectory = (file) => (file.startsWith('./') ? `.${file}` : file)
const generatedHeader = `// Generated by languages:generate. Edit languages.json.\n// oxlint-disable-next-line typescript-eslint/triple-slash-reference\n/// <reference path="../vite-assets.d.ts" />\n`

// Each language's grammar URL and query text live in one assets module that `load()` imports, so an
// app fetches one small chunk per language it uses instead of one per query file.
const queryKeys = {
  highlights: 'highlightQuerySource',
  folds: 'foldQuerySource',
  injections: 'injectionQuerySource',
  'merge-units': 'mergeUnitQuerySource',
}
const assetsModule = (id) => `${id.replaceAll(/[^a-zA-Z0-9]+/g, '-')}.assets.generated`
const languageModules = manifest.languages.flatMap((language) => {
  const queryFiles = [...new Set(Object.values(language.queries).flat())]
  const queryName = (file) => `query${queryFiles.indexOf(file)}`
  const extraWasm = Object.entries(language.extraWasm ?? {})
  const assetImports =
    `import wasmUrl from ${quote(fromLanguageDirectory(language.wasm) + '?url')}\n` +
    extraWasm
      .map(
        ([name, file]) =>
          `import ${name}WasmUrl from ${quote(fromLanguageDirectory(file) + '?url')}\n`,
      )
      .join('') +
    queryFiles
      .map(
        (file) => `import ${queryName(file)} from ${quote(fromLanguageDirectory(file) + '?raw')}\n`,
      )
      .join('')
  const queryKinds = Object.entries(language.queries)
  const joined = (sources) =>
    sources.length === 1
      ? queryName(sources[0])
      : `[${sources.map(queryName).join(', ')}].join('\\n')`
  const assetExports = queryKinds
    .filter(([, sources]) => sources.length > 0)
    .map(([kind, sources]) => `export const ${queryKeys[kind]}: string = ${joined(sources)}\n`)
    .join('')
  const extraWasmExport =
    extraWasm.length === 0
      ? ''
      : `export const extraWasmUrls: Readonly<Record<string, string>> = { ${extraWasm.map(([name]) => `${name}: ${name}WasmUrl`).join(', ')} }\n`
  const assetsContent = `${generatedHeader}${assetImports}export { wasmUrl }\n${extraWasmExport}${assetExports}`
  const parts = [`wasmUrl: assets.wasmUrl`]
    .concat(extraWasm.length === 0 ? [] : ['extraWasmUrls: assets.extraWasmUrls'])
    .concat(
      queryKinds.map(([kind, sources]) =>
        sources.length === 0
          ? `${queryKeys[kind]}: ''`
          : `${queryKeys[kind]}: mapQueryCaptures(assets.${queryKeys[kind]}, captureMappings)`,
      ),
    )
  const metadata = {
    id: language.id,
    extensions: language.extensions,
    filenames: language.filenames,
    aliases: language.aliases,
    injectionDependencies: language.injectionDependencies,
  }
  const dependencies = transitiveInjectionDependencies(language.id)
  const dependencyImports = dependencies
    .map((id) => `import { ${contributionIdentifier(id)} } from './${languageModule(id)}'\n`)
    .join('')
  const content = `// Generated by languages:generate. Edit languages.json.\nimport type { TreeSitterLanguageContribution } from '@singapore-editor/tree-sitter'\nimport { mapQueryCaptures } from '../query-captures'\nimport { captureMappings } from './capture-mappings.generated'\n${dependencyImports}export const ${contributionIdentifier(language.id)}: TreeSitterLanguageContribution = { ${quote(metadata).slice(1, -1)}, async load() {\nconst assets = await import('./${assetsModule(language.id)}');\nreturn { ${parts.join(', ')} };\n} }\nexport const ${dependencyIdentifier(language.id)}: readonly TreeSitterLanguageContribution[] = [${dependencies.map(contributionIdentifier).join(', ')}]\n`
  return [
    [`src/languages/${languageModule(language.id)}.ts`, content],
    [`src/languages/${assetsModule(language.id)}.ts`, assetsContent],
  ]
})
const catalogImports = manifest.languages
  .map(
    (language) =>
      `import { ${contributionIdentifier(language.id)} } from './languages/${languageModule(language.id)}'\n`,
  )
  .join('')

const catalogList = manifest.languages
  .map((language) => contributionIdentifier(language.id))
  .join(',\n')
const outputs = new Map([
  [
    'src/languages/capture-mappings.generated.ts',
    `// Generated by languages:generate. Edit languages.json.\nexport const captureMappings: Readonly<Record<string, string>> = ${quote(manifest.captureMappings)}\n`,
  ],
  ...languageModules,
  [
    'src/catalog.generated.ts',
    `// Generated by languages:generate. Edit languages.json.\nimport type { TreeSitterLanguageContribution } from '@singapore-editor/tree-sitter'\n${catalogImports}export const TREE_SITTER_LANGUAGE_CONTRIBUTIONS: readonly TreeSitterLanguageContribution[] = [\n${catalogList}\n]\n`,
  ],
  [
    'src/metadata.ts',
    `// Generated by languages:generate. Contains no grammar imports.\nexport const TREE_SITTER_LANGUAGE_METADATA = ${quote(manifest.languages.map(({ id, extensions, filenames, aliases, injectionDependencies, capabilities }) => ({ id, extensions, filenames, aliases, injectionDependencies, capabilities })))} as const\n`,
  ],
  [
    'languages.lock.json',
    JSON.stringify(
      { schemaVersion: 1, manifestHash: digest(JSON.stringify(manifest)), languages: locks },
      null,
      2,
    ) + '\n',
  ],
  ['NOTICE', notices.join('\n\n')],
])
// Validate every input before writing any generated output.
for (const [file, content] of outputs) {
  if (/\.(ts|json)$/.test(file)) outputs.set(file, formatTypeScript(file, content))
}
for (const [file, content] of outputs) {
  const path = resolve(root, file)
  if (check) {
    assert.equal(await readFile(path, 'utf8'), content, `Stale generated file: ${file}`)
    continue
  }
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, content)
}
// A language removed from the manifest must not leave its module behind.
const languageDirectory = resolve(root, 'src/languages')
for (const name of await readdir(languageDirectory)) {
  if (!name.endsWith('.generated.ts') || outputs.has(`src/languages/${name}`)) continue
  assert(!check, `Obsolete generated file: src/languages/${name}`)
  await rm(resolve(languageDirectory, name))
}
console.log(`${check ? 'Checked' : 'Generated'} ${manifest.languages.length} lazy languages`)

function formatTypeScript(file, input) {
  const result = spawnSync(resolve(root, 'node_modules/.bin/oxfmt'), ['--stdin-filepath', file], {
    cwd: root,
    input,
    encoding: 'utf8',
  })
  assert.equal(result.status, 0, result.stderr)
  return result.stdout
}

async function hashSourceFiles(directory, relative = '') {
  const entries = await readdir(resolve(directory, relative), { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const name = relative ? `${relative}/${entry.name}` : entry.name
    if (
      entry.isDirectory() &&
      [
        'src',
        'typescript',
        'tsx',
        'php',
        'php_only',
        'tree-sitter-markdown',
        'tree-sitter-markdown-inline',
        'tree_sitter',
        'common',
      ].includes(entry.name)
    ) {
      files.push(...(await hashSourceFiles(directory, name)))
      continue
    }
    if (!entry.isFile() || !/\.(c|cc|h|json|js)$/.test(name)) continue
    files.push({ file: name, sha256: digest(await readFile(resolve(directory, name))) })
  }
  return files.sort((left, right) => left.file.localeCompare(right.file, 'en'))
}
